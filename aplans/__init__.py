from grapple.apps import Grapple
from grapple.registry import registry
from types import MethodType


_ready = Grapple.ready  # We'll monkey-patch this
type_method_overrides = []


def override_grapple_type_method(block):
    """
    Decorator to override methods on types generated by Grapple for StreamField blocks.

    Example to define a custom resolver that overrides the method
    `resolve_my_field` of the type generated for the StreamField block MyBlock:

    ```
    @override_grapple_type_method(MyBlock)
    def resolve_my_field(self, instance, info, **kwargs):
        return 'value'
    ```
    """
    def decorator(func):
        type_method_overrides.append((block, func))
        return func
    return decorator


def _new_ready(self):
    _ready(self)
    for block, func in type_method_overrides:
        obj = getattr(registry.streamfield_blocks[block], func.__name__).__self__
        setattr(registry.streamfield_blocks[block], func.__name__, MethodType(func, obj))


Grapple.ready = _new_ready
